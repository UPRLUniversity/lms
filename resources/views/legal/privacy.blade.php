    <h2>1. Who is responsible for your data</h2>
    <p>
        {{ config('brand.university') }} is responsible for the personal information held
        about you on this platform. You can reach us at {{ config('mail.support') }}.
    </p>

    <h2>2. What we collect</h2>
    <ul>
        <li><strong>Account details</strong> — your name, email address, and anything you choose to add to your profile.</li>
        <li><strong>Learning activity</strong> — the papers you enrol on, your progress through lessons, assessment attempts and grades.</li>
        <li><strong>Submissions</strong> — the files and written work you submit for grading.</li>
        <li><strong>Purchases</strong> — orders, receipts and the payment reference returned by our payment provider.</li>
        <li><strong>Technical records</strong> — sign-in times and the network address you signed in from, kept as a security record.</li>
    </ul>
    <p>
        We do not store card numbers. Payments are handled by our payment provider, who
        returns only a reference confirming the outcome.
    </p>

    <h2>3. Why we use it</h2>
    <p>
        To give you access to what you have enrolled on, to assess your work and issue
        certificates, to take payment, to send you messages about your studies, and to
        keep the platform secure.
    </p>

    <h2>4. Who can see it</h2>
    <p>
        Your instructors can see your enrolment, progress, submissions and grades for the
        papers they teach. Administrative staff can see records necessary for running the
        institution. Other learners see only what you post in a shared discussion.
    </p>
    <p>
        Certificate verification is deliberately public: anyone holding a certificate
        serial can confirm that it is genuine and see the holder's name and the award. No
        other information is revealed.
    </p>

    <h2>5. Administrative record-keeping</h2>
    <p>
        We keep a record of consequential administrative actions — who changed a grade
        scale, who issued or revoked a certificate, who approved an enrolment — so that
        decisions affecting your studies can be accounted for. Credentials and passwords
        are never recorded in it.
    </p>

    <h2>6. How long we keep it</h2>
    <p>
        Academic records and issued certificates are kept as part of the institution's
        permanent record. Other information is kept only as long as it is needed. The
        specific retention periods will be set out here.
    </p>

    <h2>7. Your rights</h2>
    <p>
        You may ask for a copy of the information we hold about you, ask us to correct
        anything inaccurate, or ask us to delete information we no longer need. Some
        academic records must be retained even after an account is closed.
    </p>

    <h2>8. Cookies</h2>
    <p>
        We use cookies that are necessary for the platform to work: keeping you signed in,
        protecting forms against cross-site request forgery, and remembering a basket you
        have started before signing in. We do not use advertising cookies.
    </p>

    <h2>9. Changes to this policy</h2>
    <p>
        We will tell you before a material change to how we use your information takes
        effect.
    </p>
